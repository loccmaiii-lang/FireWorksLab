import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(here, '../..');
const source = path.join(root, 'experiments/ultra-baker-3.6/tool/src/js');
const hashes = {};
async function read(name) {
  const text = (await fs.readFile(path.join(source, name), 'utf8')).replace(/\r\n/g,'\n');
  hashes[name] = createHash('sha256').update(text).digest('hex');
  return text;
}
function between(text, a, b) {
  if (!text.includes(a) || !text.includes(b)) throw new Error('Ultra source boundary changed: ' + a);
  return text.slice(text.indexOf(a), text.indexOf(b));
}
await fs.mkdir(path.join(here, 'src/generated'), { recursive: true });
await fs.mkdir(path.join(here, 'vendor'), { recursive: true });
let core = '// Generated by scripts/sync-ultra.mjs from published Ultra. Do not edit.\n';
for (const file of ['00_util.js', '10_types.js', '20_sim.js', '30_plan.js']) core += await read(file) + '\n';
const quality = await read('05_quality.js');
core += between(quality, 'const QUALITY_PRESETS', 'function qualityOf');
const studies = await read('18_studies.js');
core += between(studies, 'const STUDY_RECIPES', 'function studyLayerParams');
core += between(await read('70_ui.js'), 'function derive(P)', '// 预览烘焙');
core += 'function smooth(a,b,x){const t=clamp((x-a)/(b-a),0,1);return t*t*(3-2*t);}\n';
core += between(await read('60_export.js'), 'function tintAt', 'function curvesCSV');
const trail = await read('42_trail.js');
core += between(trail, 'const TRAIL_POPS', 'const VS_TRAIL');
core += between(trail, 'function trailPeriod', '// 渲染器：draw');
const exports = ['G', 'H_STEP', 'RNG', 'Sim', 'hexToLin', 'clamp', 'defaultsFor', 'derive', 'normalizeM',
  'familyOf', 'TYPE_NAMES', 'TYPE_GROUPS', 'SCHEMA', 'measure', 'layoutOf', 'tintAt', 'colorKeys',
  'riseInfo', 'turbModes', 'shapePoints', 'STUDY_RECIPES', 'trailPeriod', 'trailPops', 'trailWaves'];
await fs.writeFile(path.join(here, 'src/generated/core.js'), core + '\nexport { ' + exports.join(', ') + ' };\n');

const gl = await read('40_gl.js');
const shaderSource = between(gl, 'const HDR =', 'const PR =') +
  between(await read('41_filaments.js'), 'const VS_FILAMENT', 'PR.filament=') +
  between(trail, 'const VS_TRAIL', 'PR.trail =');
const shaderNames = ['VS_PTS', 'FS_PTS', 'VS_SPK', 'VS_FILAMENT', 'FS_FILAMENT', 'VS_TRAIL',
  'VS_QUAD', 'FS_RGMAT', 'FS_MAT', 'VS_EMIT', 'VS_EHEAD'];
const shaderObj = vm.runInNewContext(shaderSource + '\n({' + shaderNames.join(',') + '})');
await fs.writeFile(path.join(here, 'src/generated/shaders.js'), '// Generated from Ultra shaders.\n' +
  Object.entries(shaderObj).map(([name, text]) => 'export const ' + name + ' = ' + JSON.stringify(text) + ';\n').join(''));

const coreAPI = vm.runInNewContext(core + '\n({defaultsFor,derive,STUDY_RECIPES,measure,riseInfo})', { structuredClone });
const presets = [];
for (const id of ['JM', 'V14', 'V13']) {
  const file = id === 'JM' ? 'studies/JM-fine-4k-complete.json' : 'studies/filaments/' + id + '-fine-4k-complete.json';
  const json = JSON.parse(await fs.readFile(path.join(root, 'experiments/ultra-baker-3.6', file), 'utf8'));
  presets.push({ id, name: { JM: '金芒菊', V14: '鸿巢四尺玉', V13: '片贝四尺玉' }[id],
    duration: Math.max(...json.layers.map(l => l.P.duration)), view: json.view,
    source: file, layers: json.layers.map(l => ({ id: l.id, name: l.name, P: l.P, M: l.M, expo: l.expo })) });
}
// The published root tool contains the user's approved TR2 / V5 parameters.
const mainTypes = await fs.readFile(path.join(root, 'tool/src/js/10_types.js'), 'utf8');
hashes['main@986fba1:tool/src/js/10_types.js']=createHash('sha256').update(mainTypes.replace(/\r\n/g,'\n')).digest('hex');
const mainAPI = vm.runInNewContext((await read('00_util.js')) + mainTypes +
  '\n({defaultsFor})');
for (const size of ['S', 'M', 'L']) {
  const { P, M } = mainAPI.defaultsFor('trail' + size);
  coreAPI.derive(P);
  const length = P.trV * Math.max(P.trFLife, P.trMLife, P.trCLife) * 1.4;
  const width = Math.max(3, 5 * Math.max(P.trFSpread, P.trMSpread, P.trCSpread) + P.trTwist * 3);
  presets.push({ id: 'TR2' + size, name: '升空尾缀 · ' + { S:'小', M:'中', L:'大' }[size] + ' V5',
    duration: P.duration, stop: coreAPI.riseInfo(P).ta, view: [0, -length * .45, width / 2, length * .55],
    source: 'main tool V5 / TR2 snapshot at 986fba1', layers: [{ id:'tail', name:'循环尾缀 + 逐粒消散', P, M, expo: [1,1] }] });
}
await fs.writeFile(path.join(here, 'presets.json'), JSON.stringify(presets, null, 2) + '\n');
await fs.writeFile(path.join(here, 'src/generated/sources.json'), JSON.stringify(hashes, null, 2) + '\n');
for (const name of ['three.module.js', 'three.core.js']) {
  const content=await fs.readFile(path.join(here, 'node_modules/three/build', name),'utf8');
  // One upstream line has mixed space/tab indentation; no functional change.
  await fs.writeFile(path.join(here, 'vendor', name),content.replace('\t\t\t \tmaterial = getMaterial','\t\t\t\tmaterial = getMaterial'));
}
await fs.copyFile(path.join(here, 'node_modules/three/LICENSE'), path.join(here, 'vendor/LICENSE-three.txt'));
console.log('Synced Ultra simulation, shaders, six presets and Three.js 0.186.1.');
